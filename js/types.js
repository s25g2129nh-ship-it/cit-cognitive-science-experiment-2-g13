// 相性のいいタイプ: 最初の3文字を反対にして、進め方(4文字目)は同じにする
// 例: TSDP → HVBP(自分にない視点を持ちつつ、進め方は合う相手)
const FLIP = { H: "T", T: "H", S: "V", V: "S", D: "B", B: "D", P: "P", A: "A" };
function pairOf(code) {
  return code.split("").map((c, i) => (i < 3 ? FLIP[c] : c)).join("");
}

if (typeof module !== "undefined") {
  module.exports = { TYPES, pairOf };
}
